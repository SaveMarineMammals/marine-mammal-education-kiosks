#!/bin/bash
# Pick the DRM card that has a connected HDMI output (Pi 5 has multiple cards).
# Writes /etc/X11/xorg.conf.d/99-mmek-kms-card.conf for modesetting.
set -euo pipefail

OUT_DIR="/etc/X11/xorg.conf.d"
OUT_FILE="${OUT_DIR}/99-mmek-kms-card.conf"
install -d -m 0755 "${OUT_DIR}"

CARD=""
shopt -s nullglob
for status_path in /sys/class/drm/card*-HDMI-A-*/status; do
  if [[ "$(cat "${status_path}" 2>/dev/null || true)" == "connected" ]]; then
    # card1-HDMI-A-1 -> card1
    conn="$(basename "$(dirname "${status_path}")")"
    CARD="${conn%%-*}"
    break
  fi
done

if [[ -z "${CARD}" ]]; then
  # Fallback: first card that exposes an HDMI connector name.
  for status_path in /sys/class/drm/card*-HDMI-A-*/status; do
    conn="$(basename "$(dirname "${status_path}")")"
    CARD="${conn%%-*}"
    break
  done
fi

if [[ -z "${CARD}" || ! -e "/dev/dri/${CARD}" ]]; then
  echo "mmek-select-kms-card: no HDMI DRM card found; leaving prior config" >&2
  exit 0
fi

cat > "${OUT_FILE}" <<EOF
# Generated by mmek-select-kms-card.sh — do not edit by hand.
Section "Device"
    Identifier "PiKMS"
    Driver "modesetting"
    Option "kmsdev" "/dev/dri/${CARD}"
    Option "AccelMethod" "glamor"
EndSection

Section "Screen"
    Identifier "PiScreen"
    Device "PiKMS"
EndSection
EOF

chmod 0644 "${OUT_FILE}"
echo "mmek-select-kms-card: using /dev/dri/${CARD}"
